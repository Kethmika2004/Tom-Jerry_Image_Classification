"""## **9. Predict on Test Set (with Test Time Augmentation)**

For the final test predictions, I will use ***Test Time Augmentation (TTA)*** to make the predictions a little more robust. Instead of using only the original version of each test image, the model will also predict on a few augmented versions of the same image.

The predictions from these versions will then be averaged to obtain the final class probabilities. This can help reduce the effect of small variations or noise in individual frames and may provide a small improvement in the final performance.

Since the augmentation pipeline has already been defined earlier, I can reuse it for TTA without introducing a separate preprocessing approach.
"""

test_ds_raw = make_dataset(test_meta, training=False, has_labels=False, batch_size=BATCH_SIZE)

def predict_with_tta(model, ds_raw, n_augmentations=5):
    all_preds = []

    # 1. Clean (non-augmented) pass
    base_preds = model.predict(ds_raw)
    all_preds.append(base_preds)

    # 2. Several augmented passes, averaged in
    for _ in range(n_augmentations):
        aug_ds = ds_raw.map(lambda x: data_augmentation(x, training=True))
        aug_preds = model.predict(aug_ds)
        all_preds.append(aug_preds)

    return np.mean(all_preds, axis=0)

