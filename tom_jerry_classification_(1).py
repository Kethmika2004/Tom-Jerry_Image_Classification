"""## **8.5 What Is the Model Looking At? (Grad CAM Attention Check)**

To better understand how the model is making its predictions, I will use Grad-CAM to visualize the regions of an image that contribute most to the predicted class.

This helps me check whether the model is actually focusing on meaningful areas, such as Tom and Jerry, rather than relying on unrelated features like the background, colors, or other visual artifacts. It provides an additional way to verify whether the model has learned useful visual patterns for this classification task.
"""

def get_gradcam_heatmap(img_array, model, base_model, last_conv_layer_name=None):
    if last_conv_layer_name is None:
        for layer in reversed(base_model.layers):
            if len(layer.output.shape) == 4:
                last_conv_layer_name = layer.name
                break

    grad_model = keras.Model([base_model.input], [base_model.get_layer(last_conv_layer_name).output, base_model.output])

    with tf.GradientTape() as tape:
        conv_output, predictions = grad_model(img_array)
        pooled = layers.GlobalAveragePooling2D()(predictions)
        top_class = tf.argmax(pooled[0])
        class_channel = pooled[:, top_class]

    grads = tape.gradient(class_channel, conv_output)
    pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))
    conv_output = conv_output[0]
    heatmap = conv_output @ pooled_grads[..., tf.newaxis]
    heatmap = tf.squeeze(heatmap)
    heatmap = tf.maximum(heatmap, 0) / (tf.math.reduce_max(heatmap) + 1e-8)
    return heatmap.numpy()

