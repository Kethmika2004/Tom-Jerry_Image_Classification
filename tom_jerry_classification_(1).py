"""## **5. Class Weighting**
The training data has a noticeable class imbalance, so I will use class weights during training to give more importance to the minority classes. The weights are calculated using only the training split, based on the actual number of samples available for each class.

As expected, the ```both``` class receives the highest weight because it has the fewest samples, while the ```tom_only``` class receives the lowest weight because it is the majority class. This should help reduce the model's bias towards the more frequent classes and improve its performance on the Macro F1-score.
"""

class_weights_array = compute_class_weight(
    class_weight="balanced",
    classes=np.array(CLASS_LABELS),
    y=train_files['appearance'].values
)
class_weights = dict(enumerate(class_weights_array))
print("Class weights (higher = rarer class, weighted more in the loss):")
for i, w in class_weights.items():
    print(f"  {CLASS_NAMES[i]} ({i}): {w:.3f}")

def sparse_categorical_focal_loss(gamma=2.0):
    def loss_fn(y_true, y_pred):
        y_true = tf.cast(y_true, tf.int32)
        y_pred = tf.clip_by_value(y_pred, 1e-7, 1 - 1e-7)
        ce = tf.keras.losses.sparse_categorical_crossentropy(y_true, y_pred)
        p_t = tf.gather(y_pred, y_true, batch_dims=1)
        focal_weight = tf.pow(1 - p_t, gamma)
        return focal_weight * ce
    return loss_fn

"""## **6. Model: Transfer Learning with EfficientNetB0**

For this classification task, I am using ***EfficientNetB0*** with ImageNet pretrained weights. Since the available labeled dataset is relatively small, training the complete network from scratch would not be an ideal approach.

In the first stage, I keep the EfficientNetB0 backbone frozen and train only the newly added classification layers. This allows the model to make use of the visual features learned from ImageNet while learning a new classifier specifically for the four Tom & Jerry classes.

The second stage will involve unfreezing selected higher layers of the backbone and fine-tuning them with a much smaller learning rate so that the pretrained features can gradually adapt to this dataset.
"""

num_classes = len(CLASS_LABELS)

base_model = keras.applications.EfficientNetB0(
    include_top=False, weights="imagenet", input_shape=IMG_SIZE + (3,)
)
base_model.trainable = False

inputs = keras.Input(shape=IMG_SIZE + (3,))
x = keras.applications.efficientnet.preprocess_input(inputs)
x = base_model(x, training=False)
x = layers.GlobalAveragePooling2D()(x)
x = layers.Dropout(0.35)(x)
x = layers.Dense(128, activation="relu")(x)
x = layers.Dropout(0.2)(x)
outputs = layers.Dense(num_classes, activation="softmax")(x)

model = keras.Model(inputs, outputs)
model.compile(
    optimizer=keras.optimizers.Adam(learning_rate=1e-3),
    loss=sparse_categorical_focal_loss(gamma=2.0),
    metrics=["accuracy"],
)
model.summary()

"""### **6.1 Stage A - Train the Classification Head (Backbone Frozen)**"""

callbacks = [
    keras.callbacks.EarlyStopping(monitor="val_loss", patience=5, restore_best_weights=True),
    keras.callbacks.ReduceLROnPlateau(monitor="val_loss", factor=0.5, patience=2, min_lr=1e-6),
]

EPOCHS_STAGE_A = 20

history_a = model.fit(
    train_ds, validation_data=val_ds, epochs=EPOCHS_STAGE_A,
    class_weight=class_weights, callbacks=callbacks,
)

"""### **6.2 Stage B - Fine Tune the Top Layers**"""

base_model.trainable = True
fine_tune_at = len(base_model.layers) - 30
for layer in base_model.layers[:fine_tune_at]:
    layer.trainable = False

model.compile(
    optimizer=keras.optimizers.Adam(learning_rate=1e-5),
    loss=sparse_categorical_focal_loss(gamma=2.0),
    metrics=["accuracy"],
)

EPOCHS_STAGE_B = 12

history_b = model.fit(
    train_ds, validation_data=val_ds, epochs=EPOCHS_STAGE_B,
    class_weight=class_weights, callbacks=callbacks,
)

"""## **7. Training Curves**
After training the model, I will use the training and validation curves to see how the model's performance changes over time. Looking at both loss and accuracy helps me understand whether the model is learning properly and whether it starts to overfit the training data.

These curves will also help me compare the behavior of the model across the two training stages and decide whether further training is useful.
"""

acc = history_a.history["accuracy"] + history_b.history["accuracy"]
val_acc = history_a.history["val_accuracy"] + history_b.history["val_accuracy"]
loss = history_a.history["loss"] + history_b.history["loss"]
val_loss = history_a.history["val_loss"] + history_b.history["val_loss"]
stage_boundary = len(history_a.history["accuracy"])

fig, axes = plt.subplots(1, 2, figsize=(13, 5))
axes[0].plot(acc, label="Train Accuracy"); axes[0].plot(val_acc, label="Val Accuracy")
axes[0].axvline(stage_boundary, linestyle="--", color="gray", label="Fine-tuning starts")
axes[0].set_title("Accuracy over Training"); axes[0].set_xlabel("Epoch"); axes[0].legend()

axes[1].plot(loss, label="Train Loss"); axes[1].plot(val_loss, label="Val Loss")
axes[1].axvline(stage_boundary, linestyle="--", color="gray", label="Fine-tuning starts")
axes[1].set_title("Loss over Training"); axes[1].set_xlabel("Epoch"); axes[1].legend()

plt.tight_layout()
plt.show()

"""### **7.1 Learning Rate Schedule**
Since I am using a two stage training strategy, the learning rate will also be different between the two stages. I will visualize the learning rate used during training to clearly see this change.

A relatively higher learning rate is used in the first stage to allow the newly added classification head to learn quickly. During fine tuning, the learning rate is reduced significantly so that the pretrained EfficientNet features can be adjusted gradually without making large updates that could damage the useful features already learned by the model.
"""

lr_a = history_a.history.get("learning_rate", [1e-3] * len(history_a.history["accuracy"]))
lr_b = history_b.history.get("learning_rate", [1e-5] * len(history_b.history["accuracy"]))
lr_schedule = list(lr_a) + list(lr_b)

plt.figure(figsize=(9, 4.5))
plt.plot(lr_schedule, marker="o", markersize=3, color="#E63946")
plt.axvline(stage_boundary, linestyle="--", color="gray", label="Fine-tuning starts")
plt.yscale("log")
plt.xlabel("Epoch")
plt.ylabel("Learning Rate (log scale)")
plt.title("Learning Rate Schedule Across Both Training Stages")
plt.legend()
plt.tight_layout()
plt.show()

"""## **8. Evaluation on Validation Set**
Since the competition uses Macro F1-score as the main evaluation metric, I will focus on Macro F1 rather than relying only on accuracy. This is especially important because the dataset is imbalanced and all four classes should have equal importance in the final evaluation.

I will evaluate the model on the validation set using the Macro F1-score, along with the classification report and confusion matrix, to get a better understanding of how well the model performs on each individual class.
"""

val_true = val_files['appearance'].values
val_pred_proba = model.predict(val_ds)
val_pred = np.argmax(val_pred_proba, axis=1)

macro_f1 = f1_score(val_true, val_pred, average="macro")
print(f"Validation Macro F1-score: {macro_f1:.4f}\n")
print(classification_report(val_true, val_pred, target_names=CLASS_NAMES, digits=4))

"""### **8.1 Confusion Matrix**
The confusion matrix will help me see how the model's predictions are distributed across the four classes. It shows which classes are being predicted correctly and where the model is making mistakes.

This is particularly useful for identifying cases where the model confuses similar classes, such as ```tom_only``` and ```both```, or ```jerry_only``` and ```both```. It gives a more detailed view of the model's performance than a single Macro F1-score.
"""

cm = confusion_matrix(val_true, val_pred, labels=CLASS_LABELS)
fig, ax = plt.subplots(figsize=(6.5, 6))
disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=CLASS_NAMES)
disp.plot(ax=ax, cmap="Blues", colorbar=False, xticks_rotation=45)
ax.set_title("Confusion Matrix (Validation Set)")
plt.tight_layout()
plt.show()

"""### **8.2 Per Class F1 Breakdown**
Since Macro F1 gives equal importance to all four classes, I will also look at the F1-score of each class separately. This helps me understand where the model is performing well and which classes are more difficult to predict.

In particular, I will pay attention to the ```both``` class because it has the fewest training samples. However, I will use the actual validation results to determine which class needs the most improvement rather than assuming it beforehand.
"""

per_class_f1 = f1_score(val_true, val_pred, average=None, labels=CLASS_LABELS)
per_class_df = pd.DataFrame({"class": CLASS_NAMES, "f1_score": per_class_f1,
                              "n_val_samples": [np.sum(val_true == l) for l in CLASS_LABELS]}).sort_values("f1_score")

plt.figure(figsize=(8, 5))
colors = ["#E63946" if f < macro_f1 else "#2E86AB" for f in per_class_df["f1_score"]]
bars = plt.barh(per_class_df["class"], per_class_df["f1_score"], color=colors)
plt.axvline(macro_f1, linestyle="--", color="black", label=f"Macro F1 = {macro_f1:.3f}")
plt.xlabel("F1-score"); plt.title("Per-Class F1-score (red = below average)"); plt.legend()
for bar, v in zip(bars, per_class_df["f1_score"]):
    plt.text(v + 0.01, bar.get_y() + bar.get_height()/2, f"{v:.3f}", va="center", fontweight="bold")
plt.tight_layout()
plt.show()
print(per_class_df)

"""### **8.3 Precision & Recall per Class**
The F1-score gives an overall view of a class's performance, but it does not show exactly where the mistakes are coming from. Therefore, I will also look at precision and recall for each class.

A low precision means the model is predicting that class too often and producing more false positives. A low recall means the model is missing actual examples of that class. Looking at both values helps me understand the type of errors the model is making and why a particular class may have a lower F1-score.
"""

from sklearn.metrics import precision_score, recall_score

precision_per_class = precision_score(val_true, val_pred, average=None, labels=CLASS_LABELS, zero_division=0)
recall_per_class = recall_score(val_true, val_pred, average=None, labels=CLASS_LABELS, zero_division=0)

pr_df = pd.DataFrame({
    "class": CLASS_NAMES,
    "precision": precision_per_class,
    "recall": recall_per_class,
    "f1": per_class_f1,
    "n_val_samples": [np.sum(val_true == l) for l in CLASS_LABELS],
})
print(pr_df)

fig, ax = plt.subplots(figsize=(9, 5))
x = np.arange(len(CLASS_NAMES))
width = 0.35
ax.bar(x - width/2, pr_df["precision"], width, label="Precision", color="#2E86AB")
ax.bar(x + width/2, pr_df["recall"], width, label="Recall", color="#E63946")
ax.set_xticks(x)
ax.set_xticklabels(CLASS_NAMES)
ax.set_ylabel("Score")
ax.set_title("Precision vs Recall per Class")
ax.legend()
plt.tight_layout()
plt.show()

"""### **8.4 Misclassified Examples**"""

val_images_list = []
