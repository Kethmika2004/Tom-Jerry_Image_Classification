"""## **4. CSV Driven Data Pipeline**

Since the class labels are provided in ```train.csv``` instead of being separated into different folders, I need to create the data pipeline based on the filename and label pairs in the CSV file. The pipeline will use each filename to locate the corresponding image, load it, and then prepare it with the required preprocessing before passing it to the model.

Using ```tf.data.Dataset``` will also make it easier to load the images in batches and efficiently feed them into the model during training.
"""

def load_image(filename, label=None):
    path = tf.strings.join([IMAGES_DIR, filename], separator=os.sep)
    img = tf.io.read_file(path)
    img = tf.image.decode_jpeg(img, channels=3)
    img = tf.image.resize(img, IMG_SIZE)
    if label is not None:
        return img, label
    return img

def make_dataset(df, training=False, has_labels=True, batch_size=BATCH_SIZE):
    filenames = df['filename'].values
    if has_labels:
        labels = df['appearance'].values.astype('int32')
        ds = tf.data.Dataset.from_tensor_slices((filenames, labels))
        ds = ds.map(lambda f, l: load_image(f, l), num_parallel_calls=tf.data.AUTOTUNE)
    else:
        ds = tf.data.Dataset.from_tensor_slices(filenames)
        ds = ds.map(lambda f: load_image(f), num_parallel_calls=tf.data.AUTOTUNE)

    if training:
        ds = ds.shuffle(1000, seed=RANDOM_STATE)

    ds = ds.batch(batch_size)
    ds = ds.prefetch(tf.data.AUTOTUNE)
    return ds

train_ds_raw = make_dataset(train_files, training=True)
val_ds_raw = make_dataset(val_files, training=False)

# Quick shape check
for imgs, labels in train_ds_raw.take(1):
    print("Batch image shape:", imgs.shape, " Batch label shape:", labels.shape)

"""### **4.1 Data Augmentation**
To improve the model's ability to generalize to new images, I will apply data augmentation only to the training data. Since the dataset contains noisy frames and variations in the way Tom and Jerry appear in the images, small changes such as flipping, rotation, and zooming can help the model learn more robust visual features.

The validation and test images will not be augmented, so their original visual information can be used for a fair evaluation of the model.
"""

data_augmentation = keras.Sequential([
    layers.RandomFlip("horizontal"),
    layers.RandomRotation(0.08),
    layers.RandomZoom(0.1),
    layers.RandomContrast(0.15),
    layers.RandomBrightness(0.1),
], name="augmentation")

def prep_train(ds):
    return ds.map(lambda x, y: (data_augmentation(x, training=True), y),
                  num_parallel_calls=tf.data.AUTOTUNE).prefetch(tf.data.AUTOTUNE)

train_ds = prep_train(train_ds_raw)
val_ds = val_ds_raw  # no augmentation at validation time

"""### **4.2 Visualize Augmented Samples**"""

plt.figure(figsize=(12, 6))
